"""Context window manager with sliding window and LLM-based summarization.

Sits between the agent loop and the LLM call, trimming ``messages`` to
fit within the configured token budget.  When the conversation exceeds
the summarization threshold, older messages are compressed into a short
summary generated by a cheap LLM call.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path
from typing import Any

from rich.console import Console

from axe.agent.tokens import count_messages, count_tokens
from axe.config.settings import ContextSettings

_PY_SUFFIXES = {".py", ".pyi"}
_JS_TS_SUFFIXES = {
    ".js",
    ".jsx",
    ".ts",
    ".tsx",
    ".mjs",
    ".cjs",
    ".go",
    ".rs",
    ".c",
    ".h",
    ".cc",
    ".cpp",
    ".cxx",
    ".hpp",
    ".java",
    ".kt",
    ".cs",
}

_STRUCTURAL_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"^\s*(?:import|from|use|#include|require)\b"),
    re.compile(
        r"^\s*(?:export\s+)?(?:default\s+)?(?:pub\s+)?(?:async\s+)?"
        r"(?:def|class|interface|type|struct|enum|trait|impl|fn|func|namespace|module)\b"
    ),
    re.compile(r"^\s*(?:export\s+)?(?:const|let|var)\s+\w+\s*(?::[^=]+)?=\s*(?:async\s*)?\("),
    re.compile(r"^\s*(?:public|private|protected|static|abstract|final)\s+[\w<>\[\]]+\s+\w+\s*\("),
    re.compile(r"^\s*@\w+"),
)


def compress_code_to_ast_skeleton(
    path: str,
    content: str,
    *,
    line_offset: int = 0,
) -> str:
    """Compress source code into a symbol-level skeleton.

    Python files are parsed with :mod:`ast`. Other supported languages use a
    conservative structural scanner. Function/class bodies are replaced by
    ``...`` while imports, headers, decorators, docstrings, and line spans are
    preserved. If the input cannot be parsed, a head/tail summary is returned.

    ``line_offset`` shifts emitted line spans when ``content`` is a slice of a
    larger file (for example a ``file_read`` result with ``start_line``).
    """
    suffix = Path(path).suffix.lower()
    if suffix in _PY_SUFFIXES:
        skeleton = _python_skeleton(content)
    else:
        skeleton = None
    if skeleton is None:
        skeleton = _structural_skeleton(path, content)
    return _shift_line_spans(skeleton, line_offset)


def _shift_line_spans(skeleton: str, line_offset: int) -> str:
    if line_offset <= 0:
        return skeleton

    def _replace(match: re.Match[str]) -> str:
        prefix, start, end = match.group(1), int(match.group(2)), int(match.group(3))
        return f"{prefix} lines {start + line_offset}-{end + line_offset}"

    return re.sub(r"(#|//) lines (\d+)-(\d+)", _replace, skeleton)


def _python_skeleton(content: str) -> str | None:
    try:
        tree = ast.parse(content)
    except (SyntaxError, ValueError):
        return None

    source_lines = content.splitlines()
    output: list[str] = []

    module_doc = ast.get_docstring(tree, clean=False)
    if module_doc:
        output.append('"""' + _first_line(module_doc) + '"""')
        output.append(f"# lines 1-{len(source_lines)}")

    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            output.extend(_source_segment(node, source_lines))
        elif isinstance(node, ast.ClassDef):
            output.extend(_class_skeleton(node, source_lines, ""))
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            output.extend(_function_skeleton(node, source_lines, ""))

    if not output:
        return None
    return "\n".join(line.rstrip() for line in output) + "\n"


def _source_segment(node: ast.AST, lines: list[str]) -> list[str]:
    start = getattr(node, "lineno", 1)
    end = getattr(node, "end_lineno", start)
    return [lines[index - 1] for index in range(start, min(end, len(lines)) + 1)]


def _header_lines(node: ast.AST, lines: list[str]) -> list[str]:
    start = getattr(node, "lineno", 1)
    decorators = getattr(node, "decorator_list", [])
    if decorators:
        start = min(start, *(item.lineno for item in decorators))
    body = getattr(node, "body", [])
    if body:
        if body[0].lineno <= getattr(node, "lineno", 1):
            line = lines[getattr(node, "lineno", 1) - 1]
            col = getattr(body[0], "col_offset", len(line))
            return [line[:col].rstrip()]
        header_end = body[0].lineno - 1
    else:
        header_end = getattr(node, "end_lineno", start)
    header_end = max(header_end, start)
    return [lines[index - 1] for index in range(start, min(header_end, len(lines)) + 1)]


def _docstring_line(node: ast.AST) -> str | None:
    doc = ast.get_docstring(node, clean=False)
    if not doc:
        return None
    return '"""' + _first_line(doc) + '"""'


def _function_skeleton(
    node: ast.FunctionDef | ast.AsyncFunctionDef,
    lines: list[str],
    indent: str,
) -> list[str]:
    out = _header_lines(node, lines)
    marker_indent = indent + "    "
    doc = _docstring_line(node)
    if doc:
        out.append(marker_indent + doc)
    out.append(
        f"{marker_indent}# lines {getattr(node, 'lineno', 1)}-"
        f"{getattr(node, 'end_lineno', getattr(node, 'lineno', 1))}"
    )
    out.append(f"{marker_indent}...")
    return out


def _class_skeleton(node: ast.ClassDef, lines: list[str], indent: str) -> list[str]:
    out = _header_lines(node, lines)
    marker_indent = indent + "    "
    doc = _docstring_line(node)
    if doc:
        out.append(marker_indent + doc)
    out.append(
        f"{marker_indent}# lines {getattr(node, 'lineno', 1)}-"
        f"{getattr(node, 'end_lineno', getattr(node, 'lineno', 1))}"
    )
    for child in node.body:
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out.extend(_function_skeleton(child, lines, marker_indent))
        elif isinstance(child, ast.ClassDef):
            out.extend(_class_skeleton(child, lines, marker_indent))
        elif isinstance(child, ast.AnnAssign) and isinstance(child.target, ast.Name):
            annotation = ast.unparse(child.annotation)
            value = child.value
            if isinstance(value, ast.Constant) and not isinstance(value.value, str):
                default = ast.unparse(value)
                out.append(f"{marker_indent}{child.target.id}: {annotation} = {default}")
            else:
                out.append(f"{marker_indent}{child.target.id}: {annotation}")
    out.append(f"{marker_indent}...")
    return out


def _structural_skeleton(path: str, content: str) -> str:
    """Signature-oriented fallback for non-Python source files."""
    lines = content.splitlines()
    suffix = Path(path).suffix.lower()
    headers: list[str] = []
    for index, line in enumerate(lines, start=1):
        if not line.strip():
            continue
        if any(pattern.search(line) for pattern in _STRUCTURAL_PATTERNS):
            headers.append(f"// lines {index}-{index}")
            headers.append(line.rstrip())
            if line.rstrip().endswith(("{", ":")):
                headers.append("    ...")

    if suffix not in _JS_TS_SUFFIXES:
        return content

    if len(headers) >= 4:
        return "\n".join(headers) + "\n"

    # Sparse or unparseable file: preserve the head/tail for orientation.
    head = lines[:12]
    tail = lines[-8:] if len(lines) > 20 else []
    parts = [f"// lines 1-{min(12, len(lines))}", *head]
    if headers:
        parts.extend(["// symbol headers", *headers])
    if tail:
        start = len(lines) - len(tail) + 1
        parts.extend([f"// lines {start}-{len(lines)}", *tail])
    return "\n".join(parts) + "\n"


def _first_line(text: str) -> str:
    for line in text.strip().splitlines():
        cleaned = line.strip()
        if cleaned:
            return cleaned[:160]
    return ""


_READ_LINE_PREFIX = re.compile(r"^\s*\d+\s*\|\s?", re.MULTILINE)
_READ_HEADER_RE = re.compile(r"\(lines (\d+)-\d+ of \d+\)")


def _read_start_line(output: str) -> int:
    match = _READ_HEADER_RE.search(output.splitlines()[0] if output else "")
    return int(match.group(1)) if match else 1


def _strip_read_rendering(output: str) -> str:
    """Remove ``file_read`` headers and ``NNNN | `` prefixes."""
    body: list[str] = []
    for line in output.splitlines():
        if line.startswith("--- ") and "(lines " in line:
            continue
        if line.startswith("... [Truncated"):
            continue
        body.append(_READ_LINE_PREFIX.sub("", line))
    return "\n".join(body)


class ContextManager:
    """Manage the conversation context to stay within token limits.

    Strategy:
    1. System prompt always stays (index 0).
    2. Keep the last ``keep_recent`` user+assistant+tool exchange groups.
    3. If total tokens > ``effective_target * summarize_threshold``:
       - Ask the LLM to summarize older messages.
       - Replace them with a single system-level summary message.
    4. If still over budget after summarization, aggressively truncate
       tool results (keep first + last lines).
    5. When Jev signals that AST context is sufficient (or the conversation
       is near its budget), background file bodies are replaced by skeletons.
    """

    # Prompt used to ask the LLM to summarize conversation history
    _SUMMARIZE_PROMPT = (
        "Summarize the following conversation between a user and an AI coding agent. "
        "Focus on: what the user asked, what files were read/edited, what commands ran, "
        "and the final outcome. Be concise — under 300 words.\n\n"
    )

    def __init__(
        self,
        settings: ContextSettings,
        console: Console | None = None,
    ) -> None:
        self.effective_target = settings.effective_context_target
        self.keep_recent = settings.keep_recent_messages
        self.summarize_threshold = settings.summarize_threshold
        self._console = console or Console()
        self._current_summary: str | None = None
        # Will be set externally by the agent so we can make summarization calls
        self._provider: Any = None
        self._file_contents: dict[str, tuple[str, str, int]] = {}
        self._active_files: set[str] = set()
        self._compressed_paths: set[str] = set()
        self.tokens_saved_by_ast: int = 0
        self.ast_compressions: int = 0

    def set_provider(self, provider: Any) -> None:
        """Inject the LLM provider for summarization calls."""
        self._provider = provider

    def register_file_content(self, path: str, content: str) -> None:
        """Remember a file body that may later be compressed to a skeleton."""
        if not path or not content:
            return
        self._file_contents[path] = (content, content, 0)

    def register_read_output(self, path: str, output: str) -> None:
        """Register a rendered ``file_read`` result for later compression."""
        if not path or not output:
            return
        offset = max(_read_start_line(output) - 1, 0)
        self._file_contents[path] = (
            output,
            _strip_read_rendering(output),
            offset,
        )

    def set_active_files(self, paths: set[str] | list[str]) -> None:
        """Mark files being actively edited; they keep full fidelity."""
        self._active_files = {str(path) for path in paths}

    def clear_active_files(self) -> None:
        self._active_files.clear()

    def maybe_compress_read(
        self,
        path: str,
        output: str,
        *,
        use_ast_compression: bool = False,
    ) -> str:
        """Compress a rendered ``file_read`` result when appropriate."""
        if not output or path in self._active_files:
            return output
        threshold = int(self.effective_target * self.summarize_threshold)
        if not use_ast_compression and count_tokens(output) <= int(threshold * 0.5):
            return output

        code = _strip_read_rendering(output)
        offset = max(_read_start_line(output) - 1, 0)
        skeleton = compress_code_to_ast_skeleton(path, code, line_offset=offset)
        compressed = f"--- {path} (symbol skeleton; bodies omitted) ---\n{skeleton}"
        before = count_tokens(output)
        after = count_tokens(compressed)
        if after >= before:
            return output
        self.tokens_saved_by_ast += before - after
        self.ast_compressions += 1
        return compressed

    def prepare(
        self,
        messages: list[dict[str, Any]],
        *,
        use_ast_compression: bool = False,
    ) -> list[dict[str, Any]]:
        """Return a trimmed copy of messages that fits the token budget.

        Does NOT mutate the original list — the agent keeps the full
        history for its own bookkeeping.
        """
        token_count = count_messages(messages)
        threshold = int(self.effective_target * self.summarize_threshold)

        # AST/symbol compression: explicit Jev signal, or near the budget.
        if use_ast_compression or token_count > int(threshold * 0.9):
            messages = self._compress_registered_files(messages)
            token_count = count_messages(messages)

        # Under threshold — pass through
        if token_count <= threshold:
            return list(messages)

        self._console.print(
            f"[dim]📦 Context at {token_count:,} tokens "
            f"(threshold {threshold:,}) — compressing...[/dim]"
        )

        # Split: system prompt | old history | recent messages
        system_msg = messages[0]  # always the system prompt
        recent_start = self._find_recent_start(messages)
        old_messages = messages[1:recent_start]
        recent_messages = messages[recent_start:]

        # Summarize old messages
        summary = self._summarize(old_messages)

        # Build the compressed message list
        compressed: list[dict[str, Any]] = [system_msg]

        if summary:
            compressed.append({
                "role": "system",
                "content": f"[Conversation summary so far]: {summary}",
            })

        compressed.extend(recent_messages)

        # If still over budget, truncate large tool results
        compressed = self._truncate_tool_results(compressed)

        new_count = count_messages(compressed)
        self._console.print(
            f"[dim]📦 Compressed to {new_count:,} tokens "
            f"({token_count - new_count:,} saved)[/dim]"
        )

        return compressed

    def _compress_registered_files(
        self,
        messages: list[dict[str, Any]],
    ) -> list[dict[str, Any]]:
        """Replace background file bodies with AST/symbol skeletons."""
        if not self._file_contents:
            return messages

        prepared = [dict(message) for message in messages]
        for path, (rendered, code, offset) in self._file_contents.items():
            if path in self._active_files or path in self._compressed_paths:
                continue
            if len(code.strip()) < 120:
                continue
            skeleton = compress_code_to_ast_skeleton(
                path,
                code,
                line_offset=offset,
            )
            if skeleton == code:
                continue
            before = count_tokens(rendered)
            compressed = f"--- {path} (symbol skeleton; bodies omitted) ---\n{skeleton}"
            after = count_tokens(compressed)
            if after >= before:
                continue
            replaced = False
            for index, message in enumerate(prepared):
                text = message.get("content")
                if isinstance(text, str) and rendered in text:
                    prepared[index] = {
                        **message,
                        "content": text.replace(rendered, compressed),
                    }
                    replaced = True
            if replaced:
                self._compressed_paths.add(path)
                self.tokens_saved_by_ast += before - after
                self.ast_compressions += 1
        return prepared

    def _find_recent_start(self, messages: list[dict[str, Any]]) -> int:
        """Find the index where 'recent' messages begin.

        Walks backwards from the end, counting user messages (each user
        message + its subsequent assistant/tool messages = one exchange).
        Keeps ``keep_recent`` exchanges intact.
        """
        user_count = 0
        idx = len(messages)

        for i in range(len(messages) - 1, 0, -1):
            if messages[i].get("role") == "user":
                user_count += 1
                if user_count >= self.keep_recent:
                    idx = i
                    break

        return max(idx, 1)  # Never drop the system prompt

    def _summarize(self, old_messages: list[dict[str, Any]]) -> str:
        """Use the LLM to summarize old conversation messages."""
        if not old_messages:
            return self._current_summary or ""

        # Build a text representation of old messages
        parts: list[str] = []
        for msg in old_messages:
            role = msg.get("role", "?")
            content = msg.get("content", "")
            if isinstance(content, str) and content.strip():
                # Truncate very long tool results for the summary input
                if len(content) > 2000:
                    content = content[:1000] + "\n...[truncated]...\n" + content[-500:]
                parts.append(f"[{role}]: {content}")

        conversation_text = "\n".join(parts)

        # If we have a provider, use LLM summarization
        if self._provider is not None:
            try:
                response = self._provider.complete(
                    prompt=self._SUMMARIZE_PROMPT + conversation_text,
                    system_prompt="You are a conversation summarizer. Be concise and factual.",
                )
                summary = response.text.strip()
                if summary:
                    # Merge with previous summary if exists
                    if self._current_summary:
                        summary = f"{self._current_summary}\n\nMore recently: {summary}"
                    self._current_summary = summary
                    return summary
            except Exception:
                pass  # Fall through to text-based fallback

        # Fallback: just keep a truncated version
        fallback = conversation_text[:3000]
        self._current_summary = fallback
        return fallback

    def _truncate_tool_results(
        self, messages: list[dict[str, Any]]
    ) -> list[dict[str, Any]]:
        """Aggressively truncate long tool results if still over budget."""
        result: list[dict[str, Any]] = []
        for msg in messages:
            if msg.get("role") == "tool":
                content = msg.get("content", "")
                if isinstance(content, str) and count_tokens(content) > 1000:
                    lines = content.splitlines()
                    if len(lines) > 30:
                        truncated = (
                            "\n".join(lines[:10])
                            + f"\n\n...[{len(lines) - 20} lines truncated]...\n\n"
                            + "\n".join(lines[-10:])
                        )
                        msg = {**msg, "content": truncated}
            result.append(msg)
        return result
